namespace Minotaur.Benchmarks.Labyrinth;

/// <summary>
/// Deterministic detection-corpus generator for the Minotaur-Labyrinth C#
/// rule pack (Minotaur #246, Track GSE L3). Produces, per shipped rule,
/// N vulnerable + N safe synthetic C# programs with exact ground truth
/// (rule id, file, 1-based line of the injected violation), plus safe-file
/// variants that must stay clean.
///
/// Determinism: no randomness anywhere. Program i is built from the same
/// templates for every run, so the corpus is byte-identical across machines
/// and re-generations (the ground truth needs no seed because there is no
/// chance to reproduce). Variations come from i via modular arithmetic
/// (names, sink choice, distractor choice), so the corpus exercises every
/// source/sanitizer/sink pattern of each rule.
///
/// The template bodies mirror the shapes the L2 regression corpus
/// (tests/csharp10) gate in CI, which the engine already verifies: they are
/// the patterns the rules are written against, at scale.
/// </summary>
public static class CorpusGenerator
{
    public sealed record GeneratedFile(string FileName, string Content, bool IsVulnerable);

    public sealed record GeneratedCase(
        string RuleId,
        List<GeneratedFile> Files,
        List<(string File, int Line)> ExpectedFindings,
        List<int> ExpectedLineCounts);

    /// <summary>The shipped rule ids the generator covers (rules/csharp10).</summary>
    public static readonly string[] RuleIds =
    {
        "csharp-null-deref-unguarded-maybe-null",
        "csharp-unsafe-as-cast-deref",
        "csharp-array-index-unvalidated-input",
        "csharp-divide-by-constant-zero",
        "csharp-modulo-by-constant-zero",
    };

    public static List<GeneratedCase> Generate(int pairsPerRule) =>
        RuleIds.Select(id => GenerateForRule(id, pairsPerRule)).ToList();

    private static GeneratedCase GenerateForRule(string ruleId, int pairs)
    {
        var files = new List<GeneratedFile>();
        var expected = new List<(string, int)>();
        var lineCounts = new List<int>();
        for (int i = 0; i < pairs; i++)
        {
            var (vuln, vulnLine, vulnLoc) = Render(ruleId, i, vulnerable: true);
            var vulnName = $"{ruleId}-v{i:D4}.cs";
            files.Add(new GeneratedFile(vulnName, vuln, IsVulnerable: true));
            expected.Add((vulnName, vulnLine));
            lineCounts.Add(vulnLoc);

            var (safe, _, safeLoc) = Render(ruleId, i, vulnerable: false);
            files.Add(new GeneratedFile($"{ruleId}-s{i:D4}.cs", safe, IsVulnerable: false));
            lineCounts.Add(safeLoc);
        }

        return new GeneratedCase(ruleId, files, expected, lineCounts);
    }

    /// <summary>
    /// Renders one program. Returns (source, ground-truth line of the
    /// injected violation when vulnerable, total line count). The violation
    /// line is computed, not searched, so template edits cannot silently
    /// drift from the ground truth.
    /// </summary>
    private static (string source, int violationLine, int totalLines) Render(
        string ruleId, int index, bool vulnerable)
    {
        var lines = new List<string>();
        void Add(string line = "")
        {
            lines.Add(line);
        }

        // Header (identical for every program of the family; the violation
        // therefore always sits on the same fixed line for a given body).
        Add("// Generated by Minotaur.Benchmarks.Labyrinth (deterministic; no seed).");
        Add("// Part of the issue-246 GSE L3 detection corpus (Minotaur #246).");
        Add("using System;");
        Add("using System.Collections.Generic;");
        Add("using System.Linq;");
        Add();
        Add($"public sealed class Probe{RuleIndex(ruleId):D2}{index:D4}");
        Add("{");
        int violationLine = 0;

        switch (ruleId)
        {
            case "csharp-null-deref-unguarded-maybe-null":
            {
                // Rotate the maybe-null source constructor across instances.
                var source = (index % 3) switch
                {
                    0 => $"items.FirstOrDefault()",
                    1 => $"items.SingleOrDefault()",
                    _ => $"items.Find(null)",
                };
                // Rotate the sink across the rule's sink patterns.
                var sink = (index % 5) switch
                {
                    0 => "ToString()",
                    1 => "Equals(null)",
                    2 => "GetHashCode()",
                    3 => "Clone()",
                    _ => "Dispose()",
                };
                Add($"    public string Inspect{index:D4}(List<object> items)");
                Add("    {");
                Add($"        var item = {source};");
                // Distractor: a deref of a different (guaranteed) value must not fire.
                Add("        var fallback = \"steady\";");
                Add("        var noise = fallback.Length;");
                if (vulnerable)
                {
                    violationLine = lines.Count + 1;
                    Add($"        return item.{sink};");
                }
                else
                {
                    // Safe: rotate across the rule's three guard families.
                    switch (index % 3)
                    {
                        case 0:
                            Add("        ArgumentNullException.ThrowIfNull(item);");
                            Add($"        var text = item.{sink};");
                            Add("        return text;");
                            break;
                        case 1:
                            Add("        item = item ?? fallback;");
                            Add($"        var text = item.{sink};");
                            Add("        return text;");
                            break;
                        default:
                            // Null-conditional deref only: the plain sink
                            // pattern must not match, ever, in this variant.
                            Add("        var probe = item?.ToString();");
                            Add("        var ignored = probe ?? \"-\";");
                            Add("        return ignored.Trim();");
                            break;
                    }
                }

                Add("    }");
                break;
            }

            case "csharp-unsafe-as-cast-deref":
            {
                var sink = (index % 5) switch
                {
                    0 => "ToString()",
                    1 => "Equals(null)",
                    2 => "GetHashCode()",
                    3 => "Clone()",
                    _ => "Dispose()",
                };
                var type = (index % 4) switch
                {
                    0 => "string",
                    1 => "System.IComparable",
                    2 => "object",
                    _ => "System.Text.StringBuilder",
                };
                Add($"    public string Unbox{index:D4}(object value)");
                Add("    {");
                Add($"        var item = value as {type};");
                Add("        var noise = value.ToString();");
                if (vulnerable)
                {
                    violationLine = lines.Count + 1;
                    Add($"        return item.{sink};");
                }
                else
                {
                    switch (index % 3)
                    {
                        case 0:
                            Add("        ArgumentNullException.ThrowIfNull(item);");
                            Add($"        var text = item.{sink};");
                            Add("        return text;");
                            break;
                        case 1:
                            Add("        item = item ?? \"empty\";");
                            Add($"        var text = item.{sink};");
                            Add("        return text;");
                            break;
                        default:
                            // Null-conditional deref only: the plain sink
                            // pattern must not match, ever, in this variant.
                            Add("        var probe = item?.GetHashCode();");
                            Add("        var ignored = probe ?? 0;");
                            Add("        return ignored.Value.ToString();");
                            break;
                    }
                }

                Add("    }");
                break;
            }

            case "csharp-array-index-unvalidated-input":
            {
                Add($"    public char Slot{index:D4}(string[] data)");
                Add("    {");
                Add($"        var input = Console.ReadLine();");
                Add("        var noise = data.Length;");
                if (vulnerable)
                {
                    violationLine = lines.Count + 1;
                    Add("        return data[input];");
                }
                else
                {
                    switch (index % 2)
                    {
                        case 0:
                            // Sanitizer binds the same captured node (Parse(input)).
                            Add("        var parsed = int.Parse(input);");
                            Add("        var offset = parsed % noise;");
                            Add("        return data[offset];");
                            break;
                        default:
                            Add("        int index2;");
                            Add("        int.TryParse(input, out index2);");
                            Add("        var bounded = Math.Clamp(index2, 0, noise - 1);");
                            Add("        return data[bounded];");
                            break;
                    }
                }

                Add("    }");
                break;
            }

            case "csharp-divide-by-constant-zero":
            {
                Add($"    public int Ratio{index:D4}(int total)");
                Add("    {");
                Add("        var parts = 3;");
                Add("        var noise = total / parts;");
                if (vulnerable)
                {
                    violationLine = lines.Count + 1;
                    Add("        return noise / 0;");
                }
                else
                {
                    switch (index % 2)
                    {
                        case 0:
                            Add("        var guard = parts - total % parts;");
                            Add("        return noise / guard;");
                            break;
                        default:
                            Add("        return parts == 0 ? 0 : noise / parts;");
                            break;
                    }
                }

                Add("    }");
                break;
            }

            case "csharp-modulo-by-constant-zero":
            {
                Add($"    public int Rest{index:D4}(int total)");
                Add("    {");
                Add("        var parts = 4;");
                Add("        var noise = total % parts;");
                if (vulnerable)
                {
                    violationLine = lines.Count + 1;
                    Add("        return noise % 0;");
                }
                else
                {
                    switch (index % 2)
                    {
                        case 0:
                            Add("        var guard = parts * 2;");
                            Add("        return noise % guard;");
                            break;
                        default:
                            Add("        return parts == 0 ? 0 : noise % parts;");
                            break;
                    }
                }

                Add("    }");
                break;
            }

            default:
                throw new ArgumentOutOfRangeException(nameof(ruleId), ruleId, "generator template missing");
        }

        Add("}");
        var sourceText = string.Join("\n", lines) + "\n";
        int total = lines.Count;
        if (vulnerable && violationLine == 0)
        {
            throw new InvalidOperationException($"template for {ruleId} did not inject a violation");
        }

        return (sourceText, violationLine, total);
    }

    private static int RuleIndex(string ruleId) => Array.IndexOf(RuleIds, ruleId);
}
